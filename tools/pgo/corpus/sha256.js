function sha256(bytes) {
  const h = new Int32Array([0x6a09e667|0,0xbb67ae85|0,0x3c6ef372|0,0xa54ff53a|0,
                            0x510e527f|0,0x9b05688c|0,0x1f83d9ab|0,0x5be0cd19|0]);
  const len = bytes.length;
  const withPad = ((len + 9 + 63) >> 6) << 6;
  const msg = new Uint8Array(withPad);
  msg.set(bytes);
  msg[len] = 0x80;
  const bitLen = len * 8;
  msg[withPad - 4] = (bitLen >>> 24) & 255;
  msg[withPad - 3] = (bitLen >>> 16) & 255;
  msg[withPad - 2] = (bitLen >>> 8) & 255;
  msg[withPad - 1] = bitLen & 255;

  const w = new Int32Array(64);
  for (let off = 0; off < withPad; off += 64) {
    for (let i = 0; i < 16; i++) {
      w[i] = (msg[off + i * 4] << 24) | (msg[off + i * 4 + 1] << 16) | (msg[off + i * 4 + 2] << 8) | msg[off + i * 4 + 3];
    }
    for (let i = 16; i < 64; i++) {
      const x = w[i - 15], y = w[i - 2];
      const s0 = ((x >>> 7) | (x << 25)) ^ ((x >>> 18) | (x << 14)) ^ (x >>> 3);
      const s1 = ((y >>> 17) | (y << 15)) ^ ((y >>> 19) | (y << 13)) ^ (y >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) | 0;
    }
    let a = h[0], b = h[1], c = h[2], d = h[3], e = h[4], f = h[5], g = h[6], hh = h[7];
    for (let i = 0; i < 64; i++) {
      const S1 = ((e >>> 6) | (e << 26)) ^ ((e >>> 11) | (e << 21)) ^ ((e >>> 25) | (e << 7));
      const ch = (e & f) ^ (~e & g);
      const t1 = (hh + S1 + ch + K[i] + w[i]) | 0;
      const S0 = ((a >>> 2) | (a << 30)) ^ ((a >>> 13) | (a << 19)) ^ ((a >>> 22) | (a << 10));
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (S0 + maj) | 0;
      hh = g; g = f; f = e; e = (d + t1) | 0; d = c; c = b; b = a; a = (t1 + t2) | 0;
    }
    h[0] = (h[0] + a) | 0; h[1] = (h[1] + b) | 0; h[2] = (h[2] + c) | 0; h[3] = (h[3] + d) | 0;
    h[4] = (h[4] + e) | 0; h[5] = (h[5] + f) | 0; h[6] = (h[6] + g) | 0; h[7] = (h[7] + hh) | 0;
  }
  let out = "";
  for (let i = 0; i < 8; i++) out += ((h[i] >>> 0).toString(16) + "").padStart(8, "0");
  return out;
}

