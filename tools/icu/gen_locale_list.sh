#!/usr/bin/env bash
# Regenerates src/core/engine/builtins/intl/IntlLocaleList.inc, the locales Intl reports as available: every CLDR
# locale the data blob has data for (the decimal symbols are listed because every full locale has them). Run it after
# moving the ICU4X submodule to a new release.
set -euo pipefail
cd "$(dirname "$0")/../.."
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
cargo run --release --manifest-path third_party/icu4x/provider/icu4x-datagen/Cargo.toml -- \
    --format fs --syntax json --markers DecimalSymbolsV1 --locales full -o "$tmp/data" >/dev/null 2>&1
ls "$tmp/data/decimal/symbols/v1" | sed 's/\.json$//' | python3 -c '
import re, sys
names = sorted(set(l.strip() for l in sys.stdin if l.strip()))
# The directory also lists the numbering systems the symbols are keyed by (arab, beng, ...): not locales.
locales = [n for n in names if re.fullmatch(r"[a-z]{2,3}(-[A-Za-z0-9]+)*", n) and 2 <= len(n.split("-")[0]) <= 3]
print("// Generated by tools/icu/gen_locale_list.sh from the ICU4X data; do not edit.")
for n in locales:
    print("\"%s\"," % n)
' > src/core/engine/builtins/intl/IntlLocaleList.inc
echo "[OK] $(grep -c '^"' src/core/engine/builtins/intl/IntlLocaleList.inc) locales"
